#!/usr/bin/env python3
"""Convert the Nittany Lion PNG into an RGB565 C array for the ST7789.

The source has an alpha channel (transparent outside the oval), so compositing
onto black keeps the navy oval and white lion while dropping the white box.
"""
from PIL import Image

SRC = r"C:\Users\dmyer\Downloads\213.png"
OUT = "badge_accel/logo.h"
WIDTH = 96   # height follows the source aspect ratio

im = Image.open(SRC).convert("RGBA")

# Crop to the opaque bounding box first so the logo fills the square.
bbox = im.getbbox()
im = im.crop(bbox)
# Keep the oval's proportions - the source is much wider than it is tall.
height = round(WIDTH * im.size[1] / im.size[0])
im = im.resize((WIDTH, height), Image.LANCZOS)

flat = Image.new("RGBA", im.size, (0, 0, 0, 255))
flat.alpha_composite(im)
rgb = flat.convert("RGB")

raw = rgb.tobytes()
px = [(raw[i], raw[i + 1], raw[i + 2]) for i in range(0, len(raw), 3)]
dark = sum(1 for r, g, b in px if r + g + b < 60)
navy = sum(1 for r, g, b in px if b > r + 20 and b > 40 and r + g + b < 300)
light = sum(1 for r, g, b in px if r > 180 and g > 180 and b > 180)
print(f"source bbox {bbox} -> {WIDTH}x{height}")
print(f"pixels: black-ish {dark}, navy {navy}, white-ish {light}, total {len(px)}")
if light < 200:
    raise SystemExit("ERROR: almost no white pixels - the lion did not survive")
if navy < 500:
    raise SystemExit("ERROR: almost no navy pixels - the oval did not survive")

def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

vals = [rgb565(r, g, b) for r, g, b in px]
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by make_logo.py - Penn State Nittany Lion, RGB565.\n")
    f.write("// Source: Downloads/213.png (alpha composited onto black)\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"static const int16_t LOGO_W = {WIDTH};\n")
    f.write(f"static const int16_t LOGO_H = {height};\n\n")
    f.write("static const uint16_t LOGO_RGB565[] PROGMEM = {\n")
    for i in range(0, len(vals), 12):
        row = ", ".join(f"0x{v:04X}" for v in vals[i:i + 12])
        f.write(f"  {row},\n")
    f.write("};\n")
print(f"wrote {OUT}: {len(vals)} px = {len(vals)*2} bytes")
